-- Schema khởi tạo hệ thống Quản lý bán hàng và siêu thị mini (khớp mục 2.5 docx & mục 2.7 prompt)

CREATE TABLE product (
    product_id VARCHAR(20) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    price NUMERIC(14, 0) NOT NULL CHECK (price >= 0),
    quantity INT NOT NULL CHECK (quantity >= 0),
    category VARCHAR(50) NOT NULL,
    expiry_date DATE,
    brand VARCHAR(100),
    version BIGINT DEFAULT 0 NOT NULL
);

CREATE INDEX idx_product_name ON product(name);
CREATE INDEX idx_product_category ON product(category);

CREATE TABLE invoice (
    invoice_id VARCHAR(20) PRIMARY KEY,
    invoice_date TIMESTAMP NOT NULL,
    total_amount NUMERIC(14, 0) NOT NULL CHECK (total_amount >= 0),
    discount NUMERIC(14, 0) NOT NULL DEFAULT 0 CHECK (discount >= 0),
    status VARCHAR(20) NOT NULL
);

CREATE INDEX idx_invoice_date ON invoice(invoice_date);
CREATE INDEX idx_invoice_status ON invoice(status);

CREATE TABLE invoice_detail (
    detail_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id VARCHAR(20) NOT NULL,
    product_id VARCHAR(20) NOT NULL,
    quantity INT NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(14, 0) NOT NULL CHECK (unit_price >= 0),
    subtotal NUMERIC(14, 0) NOT NULL CHECK (subtotal >= 0),
    CONSTRAINT fk_detail_invoice FOREIGN KEY (invoice_id) REFERENCES invoice(invoice_id) ON DELETE CASCADE,
    CONSTRAINT fk_detail_product FOREIGN KEY (product_id) REFERENCES product(product_id)
);

CREATE INDEX idx_invoice_detail_invoice ON invoice_detail(invoice_id);
CREATE INDEX idx_invoice_detail_product ON invoice_detail(product_id);
